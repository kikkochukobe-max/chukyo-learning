-- ============================================================
-- 語彙クロスワード: 同音異義語を同じレベルに登録できるようにする
-- Heteml(MySQL)。phpMyAdmin でDBを選び「SQL」にこの中身を貼って「実行」。1回だけ流す。
--
-- 【何が困っていたか】
--   vocab_words の UNIQUE が (level, yomi) だったため、同じレベルに
--   「ホショウ＝保証／保障／補償」のような同音異義語を1つしか置けなかった
--   （/vocab_admin.php で「このレベルに同じ読みの語がすでにあります」で弾かれる）。
--
-- 【どう直すか】
--   漢字表記(hyoki)までを重複判定に入れ、(level, yomi, hyoki) の UNIQUE にする。
--   ・保証／保障／補償 … 表記が違う＝別の語として登録できる
--   ・同じレベルに「ホショウ・保障」を2回 … これは今までどおり弾く（打ち間違い防止）
--
-- 【残る制限（承知のうえ）】
--   漢字表記が空のまま同じ読みを2つは登録できない（小学低学年向けのひらがな語など）。
--   その場合は漢字表記を入れて区別する。空欄どうしは画面上も見分けが付かないため。
--
-- ⚠ MySQL は ALTER の IF NOT EXISTS を受け付けない。既に適用済みのDBで流すと
--   #1091（uniq_level_yomi が無い）で止まる＝それは「適用済み」の意味なので放置してよい。
-- ⚠ (level, yomi) は新しいキーの先頭2列に含まれるので、読みでの絞り込みは今までどおり速い。
-- ============================================================

ALTER TABLE vocab_words
  DROP INDEX uniq_level_yomi,
  ADD UNIQUE KEY uniq_level_yomi_hyoki (level, yomi, hyoki);
