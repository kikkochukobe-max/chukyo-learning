-- 一般常識バトル: 出題単元をしぼる（部屋ごとにどの単元から出したかを残す）
-- Heteml(MySQL)。phpMyAdmin でDBを選び「SQL」にこの中身を貼って「実行」。1回だけ流す。
-- （MySQL は ALTER の IF NOT EXISTS を受け付けないので、2回流すと「列が重複」のエラーになる＝それで正常）
--
-- 講師が部屋を作るときに出題単元（ことば・漢字・算数…の10単元）を選ぶ。選んだ単元の問題だけが出る。
-- categories は単元のキーをカンマでつないだもの（例 'chiri,rekishi'）。NULL＝全部の単元から出す
-- （このSQLを流す前に作った部屋も NULL＝全単元で、実際にそうだった）。
-- このSQLを流す前に PHP だけ上げても、全単元の対戦はそのまま動く（単元をしぼった部屋が作れないだけ）。
-- ============================================================

ALTER TABLE battle_rooms
  ADD COLUMN categories VARCHAR(160) NULL DEFAULT NULL AFTER level;   -- 出題単元のキー（カンマ区切り）。NULL=全単元
