-- answer_logs に「紙で解き直すために必要なもの」を保存する列を足す
--
--   question_figure  … 問題の図（SVG／表のHTML）
--   question_choices … 選択肢（選択肢そのものが問題の中身になる型だけ）
--
-- ⚠ HetemlのMySQLは ADD COLUMN IF NOT EXISTS 非対応なので素のALTERで書いている。
--   phpMyAdmin は最初のエラーで止まるので、2本を別々に実行できるよう分けてある。
--   「Duplicate column name」＝その列はもう入っている、という意味なので、
--   そのステートメントだけ飛ばして次へ進むこと。
--
-- ▼ まず現状を確認する（返ってきた列は適用済み）
--   SHOW COLUMNS FROM answer_logs WHERE Field IN ('question_figure','question_choices');
-- ------------------------------------------------------------


-- ============================================================
-- ① question_figure … 問題の図
-- ============================================================
-- 図が無いと解けない問題（図形の角度・相似・三平方・ヒストグラム・箱ひげ図・
-- 度数分布表・理科の観察図など）を解き直しプリントで再現するための列。
--
-- question_text と同じ「人間用の表現」として、ツールが画面に出したのと同じ
-- SVG/表のHTMLをそのまま保存する。question_params から図を復元する実装を
-- PHP側に持たせない（＝サーバーに作図ロジックを置かない）原則をそのまま守る形。
--
-- 誤答（is_correct=0）のときだけ保存する。1件あたり平均1.4KB程度。
--
-- ★ 2026-08-18 時点で本番適用済み（理科4本が既にこの列を使っている）。
--   実行すると Duplicate column name になるのが正常。新しい環境を作る時だけ使う。
ALTER TABLE answer_logs
  ADD COLUMN question_figure TEXT DEFAULT NULL AFTER question_text;


-- ============================================================
-- ② question_choices … 選択肢
-- ============================================================
-- 「正しく述べたものを選ぶ」「4つの図から選ぶ」「4つの式から選ぶ」型は、
-- 選択肢そのものが問題の中身なので、問題文と図だけ刷っても紙で解き直せない。
-- そういう種類のツールだけが選択肢を送ってくる
-- （送らない種類は解き直しプリント側で記述式に直して刷る）。
--
-- 形式: [{"t":"tex","v":"…"},{"t":"svg","v":"<svg…>"}] のJSON配列。
--       t='tex' は講師ページで renderMathToHTML を通す（question_text と同じ扱い）、
--       t='svg' は図と同じホワイトリスト検証を通ってから保存される。
-- 図と同じく誤答のときだけ保存する。
ALTER TABLE answer_logs
  ADD COLUMN question_choices TEXT DEFAULT NULL AFTER question_figure;


