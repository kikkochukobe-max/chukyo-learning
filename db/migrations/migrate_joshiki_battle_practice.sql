-- 一般常識バトル: 練習モード（合算に入らない回）
-- Heteml(MySQL)。phpMyAdmin でDBを選び「SQL」にこの中身を貼って「実行」。1回だけ流す。
-- （MySQL は ALTER の IF NOT EXISTS を受け付けないので、2回流すと「列が重複」のエラーになる＝それで正常）
--
-- 講師が部屋を作るときに「本番／練習」を選ぶ。練習の回は、講師画面の「合算」（何回かの対戦の
-- 点数を足した順位）で選べない＝合算に入らない。対戦そのもの（失格・順位・結果）は本番と同じ。
-- 作ったあとでも講師画面の「これまでの部屋」から本番⇔練習を切りかえられる（付けまちがい用）。
-- このSQLを流す前に PHP だけ上げても、本番の対戦と合算はそのまま動く（練習のボタンが押せないだけ）。
-- ============================================================

ALTER TABLE battle_rooms
  ADD COLUMN is_practice TINYINT(1) NOT NULL DEFAULT 0 AFTER reveal_sec;   -- 1=練習（合算に入らない）
