-- ============================================================
-- replay_json が無い pending を掃除する（解き直し不能な行の除去）
--   対象: 「復元ではなく再表示」で解き直す単元（愛知県公立入試 大問1 など）で、
--         migrate_retry_replay.sql を当てる前／新版ファイルを上げる前にたまった行。
--   実行: phpMyAdmin の「SQL」タブに貼って実行（本番へは配信しない）
--
--   なぜ消すのか:
--     この方式の単元は retry_queue.replay_json が無いと ?retry=1 で再出題できない。
--     再出題できない＝同じ params_hash で解けない＝2連続正解が積めない＝
--     status が永久に pending のまま。生徒のマイページには件数が出るのに
--     「解き直せる問題は まだありません」しか出ない状態になる。
--     同じ問題をもう一度まちがえれば save_answer.php が埋めてくれるが、
--     生成関数が20種類以上ある単元では同じ問題を再び引く確率がほぼ無いので、
--     実際には一生埋まらない。だから消す。
--
--   ⚠ answer_logs（解いた履歴・誤答の中身）は消さない。講師ページの誤答一覧と
--     解き直しプリントはそのまま残る。ここで消すのは「解き直しキューの行」だけ。
--   ⚠ params から復元できる単元（平方根マスター等）には使わないこと。
--     あちらは replay_json が無くても question_params で再出題できるので、
--     消すと解き直せる問題を無駄に捨てることになる。
-- ============================================================

-- ------------------------------------------------------------
-- ① 消す前の確認（誰の・何問が消えるか）
-- ------------------------------------------------------------
SELECT s.login_id AS 生徒コード, s.student_name AS 生徒名,
       COUNT(*) AS 消える問題数, MIN(rq.updated_at) AS 最古, MAX(rq.updated_at) AS 最新
FROM retry_queue rq
JOIN students s ON s.student_id = rq.student_id
WHERE rq.unit_key = 'math_js3_aichi_daimon1'
  AND rq.status = 'pending'
  AND rq.replay_json IS NULL
GROUP BY rq.student_id
ORDER BY 最新 DESC;

-- ------------------------------------------------------------
-- ② 削除本体
--    replay_json IS NULL の pending だけを消す。replay がある行（＝解き直せる行）は残る。
-- ------------------------------------------------------------
DELETE FROM retry_queue
WHERE unit_key = 'math_js3_aichi_daimon1'
  AND status = 'pending'
  AND replay_json IS NULL;

